// Explicit Playwright CLI input: use a new isolated guest profile and local sample only.
async function lumioStudyV3QA(page) {
  const passed = [], errors = [], paidRequests = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); passed.push(label); };
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("request", (request) => { if (/\/api\/(?:ai|voice|transcribe)(?:\?|$)/.test(request.url())) paidRequests.push(request.url()); });
  try {
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.getByRole("button", { name: "Khám phá bài học mẫu", exact: true }).click();
    await page.locator(".lsv-toolkit").waitFor();
    check((await page.locator(".lsv-toolkit .has-content").count()) === 2, "Studio toolkit reflects the sample's real card and quiz");
    await page.locator(".lsv-reader-tools > summary").click();
    await page.getByRole("button", { name: "Cỡ chữ: 20px", exact: true }).click();
    await page.getByRole("button", { name: "Rộng", exact: true }).click();
    await page.getByRole("tab", { name: "Ghi chú", exact: true }).click();
    const notes = page.getByRole("textbox", { name: "Ghi chú", exact: true });
    const typography = await notes.evaluate((element) => ({ size: getComputedStyle(element).fontSize, line: getComputedStyle(element).lineHeight }));
    check(typography.size === "20px" && typography.line === "44px", "Reader typography applies without changing the note draft");
    await notes.fill("Bản nháp riêng của kiểm thử bài học Lumio.");
    await page.getByRole("tab", { name: "Thẻ ghi nhớ", exact: true }).click();
    await page.getByRole("button", { name: "Thêm thẻ", exact: true }).click();
    await page.getByLabel("Câu hỏi / mặt trước", { exact: true }).fill("Bài tập QA: 3 + 4 = ?");
    await page.getByLabel("Đáp án / mặt sau", { exact: true }).fill("7");
    await page.getByRole("tab", { name: "Ghi chú", exact: true }).click();
    await page.getByRole("tab", { name: "Thẻ ghi nhớ", exact: true }).click();
    check((await page.getByLabel("Câu hỏi / mặt trước", { exact: true }).inputValue()) === "Bài tập QA: 3 + 4 = ?", "Unsaved card form survives switching study tabs");
    await page.getByRole("button", { name: "Lưu thẻ", exact: true }).click();
    const card = page.locator(".lsv-flip-card");
    await card.click();
    check((await card.getAttribute("aria-pressed")) === "true", "Flashcard flip exposes the answer side");
    await page.keyboard.press("ArrowRight");
    check((await card.getAttribute("aria-pressed")) === "false" && (await card.locator(".lsv-flip-front").textContent()).includes("Bài tập QA"), "Arrow navigation advances and returns to the question");
    await page.keyboard.press("Space");
    check((await card.getAttribute("aria-pressed")) === "true", "Native Space key flips the focused card");
    check((await card.locator(".lsv-flip-front").getAttribute("aria-hidden")) === "true" && (await card.locator(".lsv-flip-back").getAttribute("aria-hidden")) === "false", "Only the active card face is exposed to assistive technology");
    await page.getByRole("tab", { name: "Ghi chú", exact: true }).click();
    await page.getByRole("tab", { name: "Thẻ ghi nhớ", exact: true }).click();
    check((await card.getAttribute("aria-pressed")) === "true" && (await card.locator(".lsv-flip-back").textContent()).includes("7"), "Card position and flip survive a tab change");
    await page.emulateMedia({ reducedMotion: "reduce" });
    check((await card.locator(".lsv-flip-inner").evaluate((element) => getComputedStyle(element).transform)) === "none", "System reduced motion removes the card's 3D transform");
    check((await card.locator(".lsv-flip-back").evaluate((element) => getComputedStyle(element).visibility)) === "visible", "Reduced motion still shows the answer immediately");
    await page.setViewportSize({ width: 375, height: 812 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Learning controls and flashcard fit 375px without horizontal overflow");
    await page.screenshot({ path: "docs/qa-study-mobile.png" });
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.emulateMedia({ reducedMotion: "no-preference" });
    await page.getByRole("tab", { name: "Bài luyện tập", exact: true }).click();
    await page.getByRole("button", { name: "Thêm câu hỏi", exact: true }).click();
    await page.getByLabel("Câu hỏi", { exact: true }).fill("Kiểm thử: 2 + 3 = ?");
    for (const [index, value] of ["5", "4", "3", "2"].entries()) await page.getByLabel(`Lựa chọn ${index + 1}`, { exact: true }).fill(value);
    await page.getByLabel("Giải thích", { exact: true }).fill("Hai cộng ba bằng năm.");
    await page.getByRole("tab", { name: "Ghi chú", exact: true }).click();
    await page.getByRole("tab", { name: "Bài luyện tập", exact: true }).click();
    check((await page.getByLabel("Câu hỏi", { exact: true }).inputValue()) === "Kiểm thử: 2 + 3 = ?", "Unsaved question form survives a tab change");
    await page.getByRole("button", { name: "Lưu câu hỏi", exact: true }).click();
    await page.getByRole("button", { name: "Bắt đầu luyện tập", exact: true }).click();
    await page.keyboard.press("b");
    check((await page.locator(".lsv-quiz-feedback.is-learning").count()) === 1, "Incorrect answer receives explicit textual feedback");
    check((await page.locator(".lm-answers button:disabled").count()) === 4, "Submitting locks answer options");
    check((await page.locator(".lsv-quiz progress").getAttribute("value")) === "1", "Quiz progress counts the answer just submitted");
    await page.getByRole("tab", { name: "Ghi chú", exact: true }).click();
    await page.getByRole("tab", { name: "Bài luyện tập", exact: true }).click();
    check((await page.locator(".lsv-quiz-feedback.is-learning").count()) === 1, "Active quiz and submitted choice survive switching tabs");
    await page.getByRole("button", { name: "Tiếp", exact: true }).click();
    await page.keyboard.press("1");
    await page.getByRole("button", { name: "Kết quả", exact: true }).click();
    check((await page.locator(".lsv-result-ring").textContent()).replace(/\s/g, "") === "1/2", "Completed quiz shows the actual one-out-of-two score");
    check((await page.locator(".lsv-answer-review article").count()) === 2 && (await page.locator(".lsv-answer-review article.is-learning").count()) === 1, "Review lists actual answers and highlights the missed question");
    await page.getByRole("tab", { name: "Ghi chú", exact: true }).click();
    await page.getByRole("tab", { name: "Bài luyện tập", exact: true }).click();
    check((await page.locator(".lsv-result-ring").textContent()).replace(/\s/g, "") === "1/2", "Quiz result survives returning from another tab");
    await page.screenshot({ path: "docs/qa-study-desktop.png" });
    await page.reload();
    await page.getByRole("button", { name: "Tìm nhanh", exact: true }).waitFor();
    await page.keyboard.press("Control+k");
    const dialog = page.locator("dialog[open]");
    await dialog.getByRole("combobox").fill("hoc cach hoc");
    await page.keyboard.press("Enter");
    await page.locator(".lsv-reader-tools > summary").click();
    check((await page.getByRole("button", { name: "Cỡ chữ: 20px", exact: true }).getAttribute("aria-pressed")) === "true", "Reader typography is restored after reloading the browser");
    await page.getByRole("tab", { name: "Ghi chú", exact: true }).click();
    check((await page.getByRole("textbox", { name: "Ghi chú", exact: true }).inputValue()) === "Bản nháp riêng của kiểm thử bài học Lumio.", "Saved notes stay in the account-scoped library after reload");
    check(paidRequests.length === 0, "The study controls and practice never call paid AI endpoints");
    check(errors.length === 0, `No runtime or hydration errors (${errors.length})`);
    return { status: "PASS", checks: passed.length, passed };
  } catch (error) { throw new Error(`After ${passed.length} study checks (${passed.at(-1) || "setup"}): ${error.message}`); }
}
